    if rest.startswith('skin.'): rest = rest[5:]
    parts = rest.split('.')
    for i in range(len(parts), 0, -1):
        base = '.'.join(parts[:i])
        if base in JA:
            words = [SKIN_WORD.get(w, w) for w in parts[i:]]
            return 'スキン引換券:' + JA[base] + '(' + '・'.join(w for w in words if w) + ')'
